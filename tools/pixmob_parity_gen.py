#!/usr/bin/env python3
"""Generate PixMob IR encoder parity-test vectors.

This is a Python port of the same encoder in
``include/pixmob_protocol.h``, used to produce the
microsecond-run-length arrays that ``test/test_pixmob_parity/`` asserts
against. Both the C++ and Python ports trace back to
github.com/jamesw343/PixMob_IR (the canonical reverse-engineered
encoder); the original five vectors in the test file were generated by
running jamesw343's Python encoder on 2026-05-06.

This script keeps that provenance chain alive: regenerating vectors no
longer requires cloning the upstream repo. If we ever want to re-verify
against jamesw343 directly, do this:

    git clone https://github.com/jamesw343/PixMob_IR /tmp/PixMob_IR
    cd /tmp/PixMob_IR
    python3 -c "from src.encoder import ..."   # use upstream API
    diff <upstream output> <this script's output>

Run::

    python3 tools/pixmob_parity_gen.py

Output: C++ array literals for the test file, ready to paste in.
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# Encoder (mirror of pixmob_protocol.h)
# ---------------------------------------------------------------------------

PULSE_US = 694

ENCODING_MAP = [
    0x21, 0x32, 0x54, 0x65, 0xa9, 0x9a, 0x6d, 0x29,
    0x56, 0x92, 0xa1, 0xb4, 0xb2, 0x84, 0x66, 0x2a,
    0x4c, 0x6a, 0xa6, 0x95, 0x62, 0x51, 0x42, 0x24,
    0x35, 0x46, 0x8a, 0xac, 0x8c, 0x6c, 0x2c, 0x4a,
    0x59, 0x86, 0xa4, 0xa2, 0x91, 0x64, 0x55, 0x44,
    0x22, 0x31, 0xb1, 0x52, 0x85, 0x96, 0xa5, 0x69,
    0x5a, 0x2d, 0x4d, 0x89, 0x45, 0x34, 0x61, 0x25,
    0x36, 0xad, 0x94, 0xaa, 0x8d, 0x49, 0x99, 0x26,
]
assert len(ENCODING_MAP) == 64


def encode_buffer_to_us(buf: list[int]) -> list[int]:
    """Encode a 6 or 9-byte buffer into a microsecond run-length list.

    Faithful port of ``encodeBufferToUs`` in pixmob_protocol.h:
      1. Apply ENCODING_MAP to buf[2..end]; accumulate a checksum.
      2. Write the checksum into buf[1] (after mapping it).
      3. Stream bits LSB-first, skipping leading zeros and trailing zeros.
      4. Run-length encode the bit stream; each run becomes count * PULSE_US.
    """
    buf = list(buf)
    checksum_sum = 0
    for i in range(2, len(buf)):
        buf[i] = ENCODING_MAP[buf[i] & 0x3F]
        checksum_sum += buf[i]
    buf[1] = ENCODING_MAP[(checksum_sum >> 2) & 0x3F]

    bits: list[bool] = []
    started = False
    for b in buf:
        for _ in range(8):
            bit = (b & 1) != 0
            if started or bit:
                bits.append(bit)
                started = True
            b >>= 1
    while bits and not bits[-1]:
        bits.pop()

    if not bits:
        return []

    out: list[int] = []
    i = 0
    while i < len(bits):
        j = i
        while j < len(bits) and bits[j] == bits[i]:
            j += 1
        out.append((j - i) * PULSE_US)
        i = j
    return out


# ---------------------------------------------------------------------------
# Time / Chance enums (mirror pixmob_protocol.h)
# ---------------------------------------------------------------------------

T_0_MS    = 0b000
T_32_MS   = 0b001
T_96_MS   = 0b010
T_192_MS  = 0b011
T_480_MS  = 0b100
T_960_MS  = 0b101
T_2400_MS = 0b110
T_3840_MS = 0b111

CHANCE_100 = 0b000
CHANCE_88  = 0b001
CHANCE_67  = 0b010
CHANCE_50  = 0b011
CHANCE_32  = 0b100
CHANCE_16  = 0b101
CHANCE_10  = 0b110
CHANCE_4   = 0b111


# ---------------------------------------------------------------------------
# Command builders (mirror pixmob_protocol.h)
# ---------------------------------------------------------------------------

def build_single_color(r, g, b, attack, sustain, release,
                       chance=CHANCE_100, restrict_group_id=0):
    buf = [0] * 9
    buf[0] = 0x80
    buf[1] = 0x00
    buf[2] = 0x00                                  # type=0b000, on_start=0
    buf[3] = (g >> 2) & 0x3F
    buf[4] = (r >> 2) & 0x3F
    buf[5] = (b >> 2) & 0x3F
    buf[6] = (attack << 3) | (chance & 0x07)
    buf[7] = (release << 3) | (sustain & 0x07)
    buf[8] = restrict_group_id & 0x1F
    return encode_buffer_to_us(buf)


def build_two_colors(r1, g1, b1, r2, g2, b2):
    buf = [0] * 9
    buf[0] = 0x80
    buf[1] = 0x00
    buf[2] = (0b010 << 1)                          # type=0b010, on_start=0
    buf[3] = (g1 >> 2) & 0x3F
    buf[4] = (r1 >> 2) & 0x3F
    buf[5] = (b1 >> 2) & 0x3F
    buf[6] = (g2 >> 2) & 0x3F
    buf[7] = (r2 >> 2) & 0x3F
    buf[8] = (b2 >> 2) & 0x3F
    return encode_buffer_to_us(buf)


def build_cycle_profiles(profile_mask, random, attack, sustain, release):
    """Cycle through enabled profile slots.

    ``profile_mask`` is the 8-bit value that the firmware port stores at
    buf[3] (low 6 bits) plus buf[4] (top 2 bits). The upstream jamesw343
    interpretation is that this is actually a ``profile_range`` field
    encoded as ``(profile_range_lo, profile_range_hi)`` rather than a
    bitmask; see architecture.md §8.2's footnote. For parity testing the
    byte-level encoding is the same regardless of interpretation, so we
    keep the original parameter name.
    """
    buf = [0] * 6
    buf[0] = 0x80
    buf[1] = 0x00
    buf[2] = (0b001 << 1)                          # type=0b001, on_start=0
    buf[3] = profile_mask & 0x3F
    buf[4] = (
        ((profile_mask >> 6) & 0x03)
        | ((1 if random else 0) << 2)
        | ((attack & 0x07) << 3)
    )
    buf[5] = (sustain & 0x07) | ((release & 0x07) << 3)
    return encode_buffer_to_us(buf)


def build_set_color(r, g, b, profile_id, is_background=False,
                    skip_display=True, restrict_group_id=0):
    buf = [0] * 9
    buf[0] = 0x80
    buf[1] = 0x00
    buf[2] = (0b111 << 1) | 1                      # type=0b111, on_start=1
    buf[3] = (g >> 2) & 0x3F
    buf[4] = (r >> 2) & 0x3F
    buf[5] = (b >> 2) & 0x3F
    buf[6] = (
        (profile_id & 0x0F)
        | ((1 if is_background else 0) << 4)
        | ((1 if skip_display else 0) << 5)
    )
    buf[7] = 0                                     # action_id
    buf[8] = restrict_group_id & 0x1F
    return encode_buffer_to_us(buf)


