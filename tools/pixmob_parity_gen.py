def format_vector_as_c(slug: str, description: str, pulses: list[int]) -> str:
    body_lines = ["// " + line for line in description.splitlines()]
    body_lines.append(f"static const uint16_t REF_{slug}[] = {{")
    chunks = []
    for i in range(0, len(pulses), 8):
        row = pulses[i:i + 8]
        chunks.append("    " + ", ".join(f"{v}" for v in row))
    body_lines.append(",\n".join(chunks))
    body_lines.append("};")
    body_lines.append(
        f"static const size_t REF_{slug}_LEN = {len(pulses)};"
    )
    return "\n".join(body_lines)


